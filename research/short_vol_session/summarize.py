def diff_ci(a_rows, b_rows, key='pnl_spread', idkeys=('ticker', 'date')):
    """Paired difference A-B on matched (ticker,date) with date-cluster bootstrap CI."""
    A = collections.defaultdict(list); B = collections.defaultdict(list)
    for r in a_rows: A[tuple(r[k] for k in idkeys)].append(float(r[key]))
    for r in b_rows: B[tuple(r[k] for k in idkeys)].append(float(r[key]))
    ks = sorted(set(A) & set(B)); d = [np.mean(A[k]) - np.mean(B[k]) for k in ks]
    if len(d) < 5: return dict(n=0)
    lo, hi = C.boot_ci(d, [k[1] for k in ks]); return dict(n=len(d), mean=round(float(np.mean(d)), 2), lo=round(lo, 2), hi=round(hi, 2))

