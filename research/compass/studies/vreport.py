"""Writes REPORT.md for V3, V4 and V8 from their result files, so no figure is copied by hand.
  python3 -I vreport.py v3|v4|v8"""
import json, os, sys
import polars as pl
HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, '..', 'results', 'v1')

def pct(v, sign=True):
    if v is None: return '—'
    s = f'{100 * v:+.1f} %' if sign else f'{100 * v:.1f} %'
    return s.replace('-', '−')

def fmt_ci(m, lo, hi):
    f = lambda v: (f'{100 * v:+.1f}').replace('-', '−')
    return f'{f(m)} % [{f(lo)}, {f(hi)}]'

def table(rows, cols):
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)]
    out += ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in rows]
    return '\n'.join(out)

def v3():
    d = os.path.join(R, 'v3_single_name_0dte')
    hold = os.path.exists(os.path.join(d, 'results_holdout.csv'))
    T = pl.read_csv(os.path.join(d, 'results_holdout.csv' if hold else 'results.csv'))
    L = ['# V3 — same-day premium on the eleven Monday/Wednesday/Friday single names (A10–A10.4)\n',
         'Generated by `studies/vreport.py v3` from `results*.csv`, `descriptive*.csv`, `trades.parquet`, `exclusions.parquet`. Returns are P&L ÷ the entry mid of the position. Intervals resample sessions. Report sessions are left out of the tests.\n']
    Tr = pl.read_parquet(os.path.join(d, 'trades.parquet')); X = pl.read_parquet(os.path.join(d, 'exclusions.parquet'))
    L.append(f'**Sample:** {Tr.height} sessions kept ({Tr.filter(~pl.col("event")).height} outside report sessions), {X.height} excluded:\n')
    L.append(table([(r, n) for r, n in X.group_by('reason').agg(pl.len()).sort('len', descending=True).iter_rows()], ['reason', 'sessions']) + '\n')
    splits = ['dev', 'val', 'devval'] + (['holdout'] if hold else [])
    rows = []
    for col, lab in (('a_r', 'V3a short straddle 10:00 → 15:50'), ('a_r_adv', '… one tick worse'), ('b_r', 'V3b short put one implied move below, to the close'),
                     ('b_r_adv', '… one tick worse'), ('c_r', 'V3c long straddle 10:00 → 15:50'), ('c_r_adv', '… one tick worse')):
        g = T.filter(pl.col('col') == col)
        cells = []
        for sp in splits:
            r = g.filter(pl.col('split') == sp)
            cells.append(fmt_ci(*r.select('mean', 'lo', 'hi').row(0)) + f' ({r["trades"][0]})' if r.height else '—')
        ph = g.filter(pl.col('split') == 'devval')['p_holm_devval'][0] if 'p_holm_devval' in g.columns else None
        rows.append([lab] + cells + [f'{ph:.3f}' if ph is not None and col in ('a_r', 'b_r', 'c_r') else ''])
    heads = {'dev': 'development 2017-06 → 2022-12', 'val': 'validation 2023–2024', 'devval': 'dev + val', 'holdout': 'hold-out 2025-01 → 2026-10'}
    L.append(table(rows, ['test'] + [heads[s] for s in splits] + ['Holm p (dev + val)']) + '\n')
    for name in ('descriptive_holdout.csv', 'descriptive.csv'):
        p = os.path.join(d, name)
        if os.path.exists(p):
            D = pl.read_csv(p)
            L.append(f'**Descriptive** (`{name}`; never tested):\n')
            piv = []
            for cut in D['cut'].unique(maintain_order=True).to_list():
                g = D.filter(pl.col('cut') == cut)
                cell = lambda c: (fmt_ci(*g.filter(pl.col('col') == c).select('mean', 'lo', 'hi').row(0)) + f" ({g.filter(pl.col('col') == c)['trades'][0]})") if g.filter(pl.col('col') == c).height else '—'
                if g['col'][0] in ('ratio', 'rel_spread'):
                    r = g.row(0, named=True); piv.append([cut, f"{r['mean']:.3f} [{r['lo']:.3f}, {r['hi']:.3f}] ({r['trades']})", '', ''])
                else: piv.append([cut, cell('a_r'), cell('b_r'), cell('c_r')])
            L.append(table(piv, ['cut', 'V3a short straddle', 'V3b short put', 'V3c long straddle']) + '\n')
            break
    open(os.path.join(d, 'REPORT.md'), 'w').write('\n'.join(L) + '\n'); print('wrote', os.path.join(d, 'REPORT.md'))

def v4():
    d = os.path.join(R, 'v4_size_forecast')
    hold = os.path.exists(os.path.join(d, 'results_holdout.csv'))
    T = pl.read_csv(os.path.join(d, 'results_holdout.csv' if hold else 'results.csv'))
    L = ['# V4 — does a price-action forecast of the session\'s move beat the same-day straddle? (A11–A11.2)\n',
         'Generated by `studies/vreport.py v4`. R = the straddle\'s implied move ÷ the forecast move; V4s sells the top tercile of R, V4l buys the bottom tercile. "minus unconditional" = the cell\'s mean minus V3\'s unconditional mean on the same sessions.\n']
    rows = []
    for (test, sp), g in T.group_by(['test', 'split'], maintain_order=True):
        r = g.row(0, named=True)
        rows.append([test, sp, r['trades'], fmt_ci(r['mean'], r['lo'], r['hi']), fmt_ci(r['minus_unconditional'], r['diff_lo'], r['diff_hi']),
                     f"{r['p_holm_devval']:.3f}" if r.get('p_holm_devval') is not None and sp == 'devval' else ''])
    L.append(table(rows, ['cell', 'split', 'trades', 'mean [95 %]', 'minus unconditional [95 %]', 'Holm p']) + '\n')
    for name, title in (('encompassing_holdout.csv' if hold else 'encompassing.csv', 'V4e — encompassing regression'), ('index_exploratory_holdout.csv' if hold else 'index_exploratory.csv', 'Index family (exploratory)')):
        p = os.path.join(d, name)
        if os.path.exists(p):
            E = pl.read_csv(p); L.append(f'**{title}** (`{name}`):\n'); L.append(table([[str(x) if not isinstance(x, float) else f'{x:.3f}' for x in r] for r in E.iter_rows()], E.columns) + '\n')
    open(os.path.join(d, 'REPORT.md'), 'w').write('\n'.join(L) + '\n'); print('wrote', os.path.join(d, 'REPORT.md'))

def v8():
    d = os.path.join(R, 'v8_monthend')
    T = pl.read_csv(os.path.join(d, 'tests.csv')); S = pl.read_parquet(os.path.join(d, 'skipped.parquet'))
    L = ['# V8 — the month-end 13:00 long straddle on chains no study here had read (A15)\n',
         'Generated by `studies/vreport.py v8`. Return = P&L ÷ the entry mid; bought at the ask, held to settlement.\n']
    rows = [[r['root'], r['days'], fmt_ci(r['mean'], r['lo'], r['hi']), f"{r['p_one_sided']:.4f}", f"{r['p_holm']:.4f}", pct(r['median']),
             fmt_ci(r['mean_adverse'], r['lo_adverse'], r['hi_adverse']), f"{r['realised_over_implied_median']:.2f}", r['by_year']] for r in T.iter_rows(named=True)]
    L.append(table(rows, ['root', 'month-ends', 'mean return [95 %]', 'one-sided p', 'Holm p', 'median', 'one tick worse', 'realised ÷ implied (median)', 'mean by year']) + '\n')
    L.append('**Skipped:**\n'); L.append(table([(a, b, c) for a, b, c in S.group_by('root', 'reason').agg(pl.len()).sort('root', 'reason').iter_rows()], ['root', 'reason', 'sessions']) + '\n')
    open(os.path.join(d, 'REPORT.md'), 'w').write('\n'.join(L) + '\n'); print('wrote', os.path.join(d, 'REPORT.md'))

if __name__ == '__main__':
    {'v3': v3, 'v4': v4, 'v8': v8}[sys.argv[1]]()
