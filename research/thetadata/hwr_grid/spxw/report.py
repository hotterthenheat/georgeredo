#!/usr/bin/env python3
"""Writes RESULTS.md from the files in results/ (numbers only from this run; no interpretation is generated here)."""
import os, json, math, datetime as dt
import numpy as np, pandas as pd
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.environ.get('RES_DIR', os.path.join(HERE, 'results'))


def md(df, cols=None, fmt='{:.4g}'):
    df = df if cols is None else df[[c for c in cols if c in df.columns]]
    def f(v):
        if isinstance(v, (float, np.floating)):
            return '' if math.isnan(v) else (fmt.format(v) if abs(v) < 1e5 else f'{v:.0f}')
        return str(v)
    return '| ' + ' | '.join(df.columns) + ' |\n|' + '---|' * len(df.columns) + '\n' + '\n'.join('| ' + ' | '.join(f(v) for v in r) + ' |' for r in df.itertuples(index=False))


def main():
    L = ['# SPXW high-win-rate grid and T-E: results (generated by report.py)\n',
         f'Generated {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M UTC} from `results/`.  Pre-registration: `PREREGISTRATION.md` (SHA-256 in `prereg_sha256.txt`).  '
         'All P&L in $ per 1-lot (one contract per leg), fills at the NBBO bid (sell) / ask (buy), $1.00 per contract per side; 95 % intervals are day-clustered percentile bootstraps (5,000 draws, seed 7).\n']
    st = json.load(open(os.path.join(RES, 'run_status.json'))) if os.path.exists(os.path.join(RES, 'run_status.json')) else {}
    if st: L.append(f"Sessions: {st.get('simulated')} of {st.get('sessions')} regular sessions simulated; missing chain files: {st.get('missing_chain')}; errors: {st.get('errors')}.\n")
    # T-C reproduction
    L.append('## 1. Sanity check: T-C reproduction (2025-06-02 → 2026-10-09)\n')
    L.append(md(pd.read_csv(os.path.join(RES, 'tc_reproduction.csv')), ['label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd', 'worst5']))
    te = json.load(open(os.path.join(RES, 'te_summary.json')))
    L.append('\nPer-session comparison with `tc_straddles.csv`: ' + ', '.join(f'{k} = {v:.4g}' if isinstance(v, float) else f'{k} = {v}' for k, v in te['tc_session_compare'].items()) + '.')
    L.append(f"  Bootstrap equivalence (vectorised vs T-C loop): {te['boot_equivalence']}.\n")
    # T-E
    L.append('## 2. T-E (pre-registered, Part A)\n')
    T = pd.read_csv(os.path.join(RES, 'te_results.csv'))
    L.append(md(T, ['label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd', 'worst5', 'verdict', 'note']))
    L.append('\nBy year:\n'); L.append(md(pd.read_csv(os.path.join(RES, 'te_by_year.csv'))))
    L.append('\nMargin and sizing (rules of T-E.4):\n')
    L.append('```\n' + json.dumps(te['sizing'], indent=1) + '\n```\n')
    # grid
    sel = json.load(open(os.path.join(RES, 'selection_train.json')))
    L.append('## 3. Grid: TRAIN selection (written before TEST was computed)\n')
    L.append(f"Selection file written {sel['written_utc']}; TRAIN sessions {sel['train_sessions']} (last {sel['train_last_date']}); eligible configurations {sel['n_eligible']} (of which TRAIN win rate ≥ 70 %: {sel['n_eligible_wr70']}).  Rule: {sel['rule']}.\n")
    S = pd.read_csv(os.path.join(RES, 'selected_test.csv'))
    cols = ['selection', 'cid', 'train_n', 'train_mean', 'train_ci_lo', 'train_ci_hi', 'train_win_rate', 'test_n', 'test_mean', 'test_ci_lo', 'test_ci_hi', 'test_win_rate', 'test_pf', 'test_max_dd', 'test_worst_day', 'test_mean_rt_cost', 'test_mean_adverse']
    L.append(md(S, cols)); L.append('')
    L.append('### Random-entry baselines (5 draws, seeds 11–15, entry uniform 10:00–14:30)\n')
    L.append(md(pd.read_csv(os.path.join(RES, 'selected_random_baseline.csv')), ['selection', 'period', 'label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd']))
    L.append('\n### Gate (plan §1) for S1 and S2 on TEST\n'); L.append(md(pd.read_csv(os.path.join(RES, 'gate.csv'))))
    L.append('\n## 4. Multiplicity over the 2,736 distinct configurations\n')
    for m in json.load(open(os.path.join(RES, 'multiplicity.json'))):
        L.append(f"- **{m['period']}**: " + '; '.join((f'{k} = {v:.4g}' if isinstance(v, float) else (f'{k} = {[round(x, 3) for x in v]}' if k.endswith('critical_values') else f'{k} = {v}')) for k, v in m.items() if k != 'period'))
    L.append('\n## 5. Win rate vs expectancy (distinct configurations with n ≥ 30)\n')
    L.append(md(pd.read_csv(os.path.join(RES, 'winrate_expectancy_tradeoff.csv'))))
    L.append('\n## 6. Rule effects, matched over all other dimensions (mean of paired differences across configurations)\n')
    L.append(md(pd.read_csv(os.path.join(RES, 'rule_effects.csv'))))
    L.append('\n## 7. Coverage (F0, no TP/stop, E2 rows; literal zero-bid rule vs wings allowed)\n')
    cv = pd.read_csv(os.path.join(RES, 'coverage.csv'))
    L.append(md(cv, ['period', 'cell', 'entry', 'sessions', 'trades_literal', 'coverage_literal', 'trades_wing0_allowed', 'skip_out_of_band', 'skip_zero_bid_short', 'skip_zero_bid_wing', 'skip_no_quote', 'skip_no_credit']))
    L.append('\n## 8. TEST win rate ≥ 70 % and TEST lower bound > 0 (all distinct configurations; descriptive, not train-selected)\n')
    w = pd.read_csv(os.path.join(RES, 'test_wr70_lbpos.csv'))
    L.append(f'{len(w)} configurations.\n')
    if len(w): L.append(md(w.head(40), ['cid', 'train_n', 'train_mean', 'train_ci_lo', 'train_win_rate', 'test_n', 'test_mean', 'test_ci_lo', 'test_ci_hi', 'test_win_rate', 'test_pf', 'test_worst_day']))
    L.append('\n## 8b. Post-hoc data-limitation check: strangle days skipped because the strike lay outside the stored band (`bandcheck.py`)\n')
    bc = pd.read_csv(os.path.join(RES, 'band_bias_check.csv'))
    L.append('Naked, no-TP, no-stop, E2 configurations; skipped out-of-band days added back with (a) a strict optimistic bound (credit = ATM straddle credit), (b) an optimistic estimate (credit = max observed strangle/straddle credit ratio × straddle credit), (c) a pessimistic bracket (zero credit).\n')
    L.append(md(bc[bc['period'] == 'TEST'].sort_values('ci_lo', ascending=False).head(30), ['cid', 'n', 'mean', 'ci_lo', 'win_rate', 'oob_days_added', 'worst_added', 'ci_lo_with_bound', 'mean_ratio_est', 'ci_lo_ratio_est', 'ci_lo_zero_credit']))
    L.append('\n## 8c. Data diagnostics (`diag.py`)\n')
    dg = pd.read_csv(os.path.join(RES, 'diagnostics.csv'))
    L.append(md(dg[~dg['metric'].str.startswith('EM median')]))
    L.append('\n## 9. Sizing for configurations with TEST lower bound > 0 (G.8)\n')
    sz = pd.read_csv(os.path.join(RES, 'sizing_test_lbpos.csv'))
    L.append(f'{sz["cid"].nunique() if len(sz) else 0} configurations; full table in `results/sizing_test_lbpos.csv`.\n')
    if len(sz): L.append(md(sz.head(60)))
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('RESULTS.md written', sum(len(x) for x in L))


if __name__ == '__main__':
    main()
