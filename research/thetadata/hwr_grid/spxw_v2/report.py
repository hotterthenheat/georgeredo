#!/usr/bin/env python3
"""Writes RESULTS.md (v2) from the files in results/ (numbers only from this run and from ../spxw/results; no interpretation)."""
import os, json, math, datetime as dt
import numpy as np, pandas as pd
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.environ.get('RES_DIR', os.path.join(HERE, 'results'))


def md(df, cols=None, fmt='{:.4g}'):
    df = df if cols is None else df[[c for c in cols if c in df.columns]]
    def f(v):
        if isinstance(v, (float, np.floating)):
            return '' if math.isnan(v) else (fmt.format(v) if abs(v) < 1e5 else f'{v:.0f}')
        return str(v).replace('|', '\\|') if isinstance(v, str) else str(v)
    return '| ' + ' | '.join(df.columns) + ' |\n|' + '---|' * len(df.columns) + '\n' + '\n'.join('| ' + ' | '.join(f(v) for v in r) + ' |' for r in df.itertuples(index=False))


def rd(name, **kw): return pd.read_csv(os.path.join(RES, name), **kw)


def main():
    L = ['# SPXW short-premium study v2 (complete chains, Cboe settlement): results (generated by report.py)\n',
         f'Generated {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M UTC} from `results/`.  Design: `../spxw/PREREGISTRATION.md`, unchanged; the two input changes and the '
         'added analyses are listed in `README.md` (protocol hash in `protocol_sha256.txt`).  P&L in $ per 1-lot (one contract per leg), sell at the NBBO bid / buy at the ask, '
         '$1.00 per contract per side, settlement at the official Cboe SPX close; 95 % intervals are day-clustered percentile bootstraps (5,000 draws, seed 7).  '
         '"v1" = the round-2 study (`../spxw/results`, ±2 % band chains, 16:00 print).\n']
    st = json.load(open(os.path.join(RES, 'run_status.json'))) if os.path.exists(os.path.join(RES, 'run_status.json')) else {}
    if st: L.append(f"Sessions: {st.get('simulated')} of {st.get('sessions')} regular sessions simulated; missing chain files: {st.get('missing_chain')}; errors: {st.get('errors')}.\n")
    # 0 Amendment 1 resolution
    if os.path.exists(os.path.join(RES, 'resolution_changes.csv')):
        D = pd.read_csv(os.path.join(RES, 'resolution_changes.csv'), low_memory=False)
        L.append('## 0. Amendment 1 resolved: 2024-06-21 now on its complete chain\n')
        L.append('The complete 2024-06-21 file arrived at 03:03 UTC (fetch retry).  Its band-fallback trade/skip files were deleted and the whole pipeline re-run '
                 '(`protocol_sha256.txt`).  Every changed cell, before → after, is in `results/resolution_changes.csv` (written by `resolution_diff.py` against the '
                 'pre-resolution snapshot).  **No TEST-period figure changed** (0 changed TEST rows or `test_*` columns in any table; `gate.csv` identical); '
                 'the S1/S2 selections and the TRAIN top 10 are unchanged.  Changes are confined to TRAIN, the T-E window baseline and whole-sample figures:\n')
        pick = []
        sel = D[(D['file'] == 'selected_test.csv') & D['key'].str.match(r'^(S1|S2|orig_S2|TE_rule) ') & D['column'].isin(['train_n', 'train_mean', 'train_ci_lo', 'train_ci_hi'])]
        te = D[(D['file'] == 'te_results.csv') & D['column'].isin(['mean', 'ci_lo', 'ci_hi']) & D['key'].str.contains('lane minus')]
        mu = D[(D['file'] == 'multiplicity.json') & D['key'].str.match(r'^\[0\]\.(observed_lb_gt0|chance_mean|chance_p95|fixed_se_romano_wolf_rejections|within_draw_se_reality_check_p)$')]
        ig = D[(D['file'] == 'integrity_summary.json') & ~D['key'].isin(['fixed_and_random_not_ok_list']) & ~D['key'].str.startswith('allmin_nonok_by_reason_cell')]
        cr = D[(D['file'] == 'capital_returns.csv') & D['column'].isin(['ann_return_on_median_capital_pct'])]
        rx = D[(D['file'] == 'cmp_random_explain.csv') & D['key'].str.contains('lane minus random \\(all') & (D['column'] == 'mean')]
        cg = D[(D['file'] == 'carry_gate.csv') & (D['column'] != 'data_integrity')]
        for x in (ig, sel, te, rx, mu, cr, cg): pick.append(x)
        L.append(md(pd.concat(pick)[['file', 'key', 'column', 'before', 'after']], fmt='{:.6g}'))
        L.append('\nNote: the complete 2024-06-21 file is itself partial (127 of 333 strikes carry one side only; 7,429 rows of the band file are absent from it; '
                 'at 14:05 the rounded ATM strike had no usable call/put pair and the k = 0.5 short strikes landed 8.37 / 7.63 points beyond their targets).  '
                 'Pre-resolution RESULTS.md is kept as `$SP/hwr_grid/spxw_v2/results_amend1/RESULTS_amend1.md` (scratchpad).\n')
    # 1 integrity
    I = json.load(open(os.path.join(RES, 'integrity_summary.json')))
    L.append('## 1. Data integrity of the complete chains (`integrity.py`)\n')
    L.append('```\n' + json.dumps({k: v for k, v in I.items() if k not in ('fixed_and_random_not_ok_list',)}, indent=1, default=str) + '\n```\n')
    L.append('Entries whose structure could not be built (fixed entries and committed random minutes; first 200):\n')
    L.append('```\n' + '\n'.join(I.get('fixed_and_random_not_ok_list', [])) + '\n```\n')
    L.append('By k (fixed = 10:00/11:00/13:00/14:05; random = R1..R5 committed minutes).  `*_beyond_listed` = no listed strike at/beyond the target; `*_not_usable` = listed but no usable quote row at the entry minute; `*_outside_band_v1` = the strike the complete chain uses was not stored in the round-2 band file; `*_gap_gt5` = nearest listed strike outward more than 5 points beyond the target.\n')
    L.append(md(rd('integrity_by_k.csv')))
    nm = rd('integrity_minutes_nonok.csv')
    L.append(f'\nEvery minute 10:00–14:30 × 8 structure cells: {len(nm)} non-buildable (minute, cell) cases; by reason and cell: ' +
             (', '.join(f'{k} {v}' for k, v in nm.groupby(['reason', 'cell']).size().items()) if len(nm) else 'none') + '.\n')
    if len(nm): L.append(md(nm.groupby(['date', 'reason']).size().reset_index(name='minute_cells').sort_values('minute_cells', ascending=False).head(30)))
    # 2 T-C + T-E
    L.append('\n## 2. T-C reproduction and T-E on complete data\n')
    L.append(md(rd('tc_reproduction.csv'), ['label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd', 'worst5']))
    te = json.load(open(os.path.join(RES, 'te_summary.json')))
    L.append('\nPer-session comparison with `tc_straddles.csv`: ' + ', '.join(f'{k} = {v:.4g}' if isinstance(v, float) else f'{k} = {v}' for k, v in te['tc_session_compare'].items()) + '.\n')
    L.append(md(rd('te_results.csv'), ['label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd', 'worst5', 'verdict', 'note']))
    L.append('\nBy year:\n'); L.append(md(rd('te_by_year.csv')))
    L.append('\nT-E side by side with v1:\n')
    L.append(md(rd('cmp_te.csv'), ['window', 'item', 'v1_n', 'v1_mean', 'v1_ci_lo', 'v1_ci_hi', 'v1_win_rate', 'v1_max_dd', 'v2_n', 'v2_mean', 'v2_ci_lo', 'v2_ci_hi', 'v2_win_rate', 'v2_max_dd', 'v2_verdict', 'v2_note']))
    L.append('\nMargin and sizing under the pre-stated T-E.4 rules (complete data):\n')
    L.append('```\n' + json.dumps({k: v for k, v in te['sizing'].items() if k in ('T-E window', 'holdout', 'kelly_from_TE_window', 'tail_sizing_fixed_capital_TE_median')}, indent=1) + '\n```\n')
    # 3 grid
    sel = json.load(open(os.path.join(RES, 'selection_train.json')))
    L.append('## 3. Grid: TRAIN selection on complete data, TEST, and the round-2 definitions\n')
    L.append(f"Selection file written {sel['written_utc']} (before the TEST stage); TRAIN sessions {sel['train_sessions']}; eligible {sel['n_eligible']} (TRAIN win ≥ 70 %: {sel['n_eligible_wr70']}).\n")
    L.append(md(rd('cmp_selection.csv'), ['study', 'selection', 'cid', 'train_n', 'train_mean', 'train_ci_lo', 'train_ci_hi', 'train_win_rate', 'test_n', 'test_mean', 'test_ci_lo', 'test_ci_hi',
                                           'test_ci_lo_bonf2', 'test_win_rate', 'test_pf', 'test_max_dd', 'test_worst_day', 'test_mean_rt_cost', 'test_mean_adverse', 'lane_minus_random', 'PASS_all', 'CARRY_stat_items']))
    S = rd('selected_test.csv')
    L.append('\nTRAIN top 10 (complete data) on TEST:\n')
    L.append(md(S[S['selection'].str.startswith('top')], ['selection', 'cid', 'train_n', 'train_mean', 'train_ci_lo', 'train_win_rate', 'test_n', 'test_mean', 'test_ci_lo', 'test_ci_hi', 'test_win_rate', 'test_worst_day']))
    L.append('\n### Random-entry baselines (seeds 11–15) with matched-day and pooled figures\n')
    L.append(md(rd('selected_random_baseline.csv'), ['selection', 'period', 'label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'pf', 'max_dd']))
    L.append('\nv1 random baselines for comparison:\n')
    b = rd('cmp_random_baseline.csv'); L.append(md(b[b['study'] == 'v1'], ['selection', 'period', 'label', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate']))
    L.append('\n### Why lane − random changed between v1 and v2 (`cmp_random_explain.csv`, `cmp_random_shortdays.csv`)\n')
    L.append(md(rd('cmp_random_explain.csv'), ['label', 'period', 'item', 'n', 'mean', 'note'], fmt='{:.5g}'))
    L.append('\n### Robustness of the compared rules on complete data (`cmp_robustness.csv`)\n')
    L.append(md(rd('cmp_robustness.csv'), ['label', 'period', 'item', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'note'], fmt='{:.5g}'))
    L.append('\n### Gate (plan §1, unchanged code) and carry items\n'); L.append(md(rd('gate.csv')))
    L.append('\n## 4. Multiplicity (2,736 distinct configurations), v1 vs v2\n')
    L.append(md(rd('cmp_multiplicity.csv')))
    L.append('\n## 5. Where v1 and v2 differ: band-skipped days and the settlement source (`compare.py`)\n')
    L.append(md(rd('cmp_decomposition.csv'), ['label', 'period', 'series', 'n', 'mean', 'ci_lo', 'ci_hi', 'win_rate', 'total', 'detail'], fmt='{:.5g}'))
    # 6 stress
    L.append('\n## 6. Tail stress, margin, capital and drawdowns (`stress.py`)\n')
    meta = json.load(open(os.path.join(RES, 'stress_meta.json')))
    L.append(f"Configurations: {meta['configs']}.  Worst-move series: {meta['worst_moves_series']}.\n")
    L.append('### Worst historical SPX moves, entry → close, 2017-06-01 → 2026-10-09 (regular sessions)\n')
    W = rd('worst_moves.csv'); L.append(md(W[W['rank'] <= 5]))
    ss = rd('stress_summary.csv')
    L.append('\n### Settlement P&L under SPX shocks from the entry level ($ per lot; median and worst over trades; and at the last trade)\n')
    keep = ['label', 'period', 'n', 'spot_median', 'credit_median_pts', 'actual_mean', 'actual_worst', 'actual_worst_date'] + [c for c in ss.columns if c.startswith('shock') and (c.endswith('_median') or c.endswith('_worst'))]
    L.append(md(ss, keep))
    L.append('\nAt the last trade:\n'); L.append(md(ss[ss['period'] == 'ALL'], ['label', 'last_date', 'last_spot'] + [c for c in ss.columns if c.endswith('_last')]))
    L.append('\n### Margin and capital per lot\n'); L.append(md(rd('margin_summary.csv')))
    L.append('\n### Annualised return on the stress capital\n'); L.append(md(rd('capital_returns.csv')))
    L.append('\n### Drawdowns at that sizing (circular block bootstrap of the complete-data daily return series, 3,000 paths, seed 7)\n')
    L.append(md(rd('drawdown_bootstrap.csv'), ['label', 'capital_rule', 'source', 'block', 'horizon_sessions', 'hist_maxdd', 'hist_longest_underwater', 'median_maxdd', 'p95_maxdd',
                                                 'p_dd_gt10', 'p_dd_gt20', 'p_dd_gt30', 'p_dd_gt50', 'median_longest_underwater', 'p95_longest_underwater', 'p_end_below_start']))
    L.append('\n## 7. COMPASS §10 carry-lane gate items (`carry_gate.csv`)\n')
    L.append(md(rd('carry_gate.csv')))
    # secondary
    L.append('\n## 8. Secondary pre-registered outputs on complete data\n')
    L.append('### Win rate vs expectancy\n'); L.append(md(rd('winrate_expectancy_tradeoff.csv')))
    L.append('\n### Rule effects\n'); L.append(md(rd('rule_effects.csv')))
    L.append('\n### Coverage\n'); cv = rd('coverage.csv')
    L.append(md(cv, ['period', 'cell', 'entry', 'sessions', 'trades_literal', 'coverage_literal', 'trades_wing0_allowed', 'skip_out_of_band', 'skip_zero_bid_short', 'skip_zero_bid_wing', 'skip_no_quote', 'skip_no_credit']))
    L.append('\n### Diagnostics\n'); dg = rd('diagnostics.csv'); L.append(md(dg[~dg['metric'].str.startswith('EM median')]))
    w = rd('test_wr70_lbpos.csv')
    L.append(f'\n### TEST win rate ≥ 70 % and TEST lower bound > 0 (all distinct configurations; descriptive): {len(w)} configurations\n')
    if len(w): L.append(md(w.head(30), ['cid', 'train_n', 'train_mean', 'train_ci_lo', 'train_win_rate', 'test_n', 'test_mean', 'test_ci_lo', 'test_ci_hi', 'test_win_rate', 'test_worst_day']))
    sz = rd('sizing_test_lbpos.csv')
    L.append(f'\n### G.8 sizing for TEST lower bound > 0 configurations: {sz["cid"].nunique() if len(sz) else 0} configurations (full table `results/sizing_test_lbpos.csv`)\n')
    if len(sz):
        s8 = sz[sz['rule'].str.startswith('max-loss')]
        L.append(md(s8.sort_values('test_ci_lo', ascending=False).head(15), ['cid', 'test_n', 'test_mean', 'test_ci_lo', 'loss_basis', 'capital', 'actual_maxdd', 'boot_median_dd', 'p_dd_gt20', 'p_end_below_start']))
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('RESULTS.md written', sum(len(x) for x in L))


if __name__ == '__main__':
    main()
